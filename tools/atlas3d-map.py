#!/usr/bin/env python3
# Converts Natural Earth 1:50m admin-0 countries into the atlas3d map module: world.js (arcs, countries, transform)
# and index.json (valid country codes with name and bbox). With --relief, it also writes relief.webp from Natural
# Earth Shaded Relief through ffmpeg. Developer tool. It is not copied into projects and is not in the npm package.
# Python stdlib only; ffmpeg is needed only for --relief.
# Usage: python3 tools/atlas3d-map.py [--out-dir DIR] [--relief]
import argparse
import hashlib
import json
import math
import os
import re
import shutil
import subprocess
import urllib.request
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_OUT = os.path.join(ROOT, "skills", "scene-flow", "assets", "atlas3d", "map")
CACHE_DIR = os.path.expanduser("~/.cache/scene-flow/natural-earth")

RELEASE = "v5.1.2"
COUNTRIES = "ne_50m_admin_0_countries.geojson"
COUNTRIES_URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/%s/geojson/%s" % (RELEASE, COUNTRIES)
COUNTRIES_SHA256 = "3e458fc036ad0a66411f2c1e6cac49c5d7bfb81cb1123bc513b22511a2b7fdeb"
RELIEF_ZIP = "SR_50M.zip"
RELIEF_URL = "https://naciscdn.org/naturalearth/50m/raster/SR_50M.zip"
RELIEF_SHA256 = "ff810f5f2747463fd8ffa612b23e5f5e5d593a345218976872b6749610976ab7"
RELIEF_TIF = "SR_50M.tif"  # GeoTIFF member of the archive, 10800 x 5400, 8-bit grey, WGS 84 plate carree
RELIEF_FILTER = "scale=4096:2048:flags=lanczos"
RELIEF_QUALITY = "75"

GRID = 1000         # quantization steps per degree: 0.001 degree, about 111 m
SIMPLIFY = 10       # Douglas-Peucker tolerance in grid steps: 0.01 degree
MIN_AREA_KM2 = 2.0  # outer rings below this are dropped and printed; a country's largest polygon is always kept
KM_PER_DEGREE = 111.32
CODE_RE = re.compile(r"^[A-Z]{3}$")

HEADER = """// Natural Earth 1:50m admin-0 countries, release %s, public domain. Generated by tools/atlas3d-map.py; do not edit.
// Points are integers on a grid of 1/%d degree: lon = q / %d - 180, lat = q / %d - 90.
// transform: x = q * scale + translate, applied to the grid values.
// arcs: each arc is a list of points. The first point is absolute; each later point is a delta from the point before.
// ring: list of arc references. k is arcs[k] in order; ~k is arcs[k] reversed.
// countries[CODE]: name, bbox [minLon, minLat, maxLon, maxLat], polygons. A polygon is [outerRing, holeRing, ...].
// Shared borders are one arc, so neighbouring countries reference the same points.
"""


def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def cached(name, url, sha256):
    os.makedirs(CACHE_DIR, exist_ok=True)
    path = os.path.join(CACHE_DIR, name)
    if not os.path.exists(path):
        part = path + ".part"
        with urllib.request.urlopen(url, timeout=300) as resp, open(part, "wb") as out:
            shutil.copyfileobj(resp, out)
        os.replace(part, path)
    digest = sha256_of(path)
    if digest != sha256:
        raise SystemExit("%s: SHA-256 %s does not match the pinned %s; delete %s to download it again"
                         % (name, digest, sha256, path))
    return path


def quantize(coords):
    pts = []
    for lon, lat in coords:
        p = (round((lon + 180) * GRID), round((lat + 90) * GRID))
        if not pts or pts[-1] != p:
            pts.append(p)
    while len(pts) > 1 and pts[-1] == pts[0]:
        pts.pop()
    return pts


def load_countries(path):
    with open(path, encoding="utf-8") as f:
        features = json.load(f)["features"]
    countries = {}
    for feat in features:
        props = feat["properties"]
        code = props.get("ADM0_A3")
        if code is None or code == "-99" or not CODE_RE.match(code):
            raise SystemExit("feature %r has no usable ADM0_A3 code: %r" % (props.get("NAME"), code))
        if code in countries:
            raise SystemExit("duplicate ADM0_A3 code %s" % code)
        geom = feat["geometry"]
        polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        countries[code] = {"name": props["NAME"], "polygons": [[quantize(ring) for ring in poly] for poly in polys]}
    return countries


def area_km2(ring):
    n = len(ring)
    if n < 3:
        return 0.0
    lat0 = math.radians(sum(y for _, y in ring) / n / GRID - 90)
    xs = [(x / GRID - 180) * math.cos(lat0) * KM_PER_DEGREE for x, _ in ring]
    ys = [(y / GRID - 90) * KM_PER_DEGREE for _, y in ring]
    twice = sum(xs[i] * ys[(i + 1) % n] - xs[(i + 1) % n] * ys[i] for i in range(n))
    return abs(twice) / 2


def drop_small(code, polygons):
    # Holes are kept at any size: a hole is often a neighbour's territory (Vatican in Italy), and dropping it
    # would leave that area filled by the surrounding country.
    areas = [area_km2(poly[0]) for poly in polygons]
    keep = [a >= MIN_AREA_KM2 for a in areas]
    if not any(keep):
        keep[areas.index(max(areas))] = True
    kept = []
    for poly, area, ok in zip(polygons, areas, keep):
        if not ok:
            print("dropped %s polygon: outer ring %.2f km2, %d hole(s)" % (code, area, len(poly) - 1))
            continue
        if len(poly[0]) < 3:
            raise SystemExit("%s: outer ring has fewer than 3 distinct grid points" % code)
        kept.append(poly)
    return kept


def edge_key(a, b):
    return (a, b) if a <= b else (b, a)


def topology(countries):
    owners = {}
    neighbours = {}
    for code in sorted(countries):
        for poly in countries[code]["polygons"]:
            for ring in poly:
                n = len(ring)
                for i in range(n):
                    a, b = ring[i], ring[(i + 1) % n]
                    owners.setdefault(edge_key(a, b), set()).add(code)
                    neighbours.setdefault(a, set()).add(b)
                    neighbours.setdefault(b, set()).add(a)
    return owners, neighbours


def ring_arcs(ring, owners, neighbours):
    # A vertex cuts the ring where it has other than two neighbours, or where the countries on its two edges differ.
    n = len(ring)
    keys = [edge_key(ring[i], ring[(i + 1) % n]) for i in range(n)]
    cuts = [i for i in range(n) if len(neighbours[ring[i]]) != 2 or owners[keys[i - 1]] != owners[keys[i]]]
    if not cuts:
        cuts = [ring.index(min(ring))]
    arcs = []
    for k, start in enumerate(cuts):
        end = cuts[(k + 1) % len(cuts)]
        seq = [ring[start]]
        i = start
        while True:
            i = (i + 1) % n
            seq.append(ring[i])
            if i == end:
                break
        arcs.append(seq)
    return arcs


def assign_arcs(countries, owners, neighbours):
    ids = {}
    arcs = []
    table = {}
    for code in sorted(countries):
        polygons = []
        pts = [p for poly in countries[code]["polygons"] for ring in poly for p in ring]
        bbox = [min(x for x, _ in pts), min(y for _, y in pts), max(x for x, _ in pts), max(y for _, y in pts)]
        for poly in countries[code]["polygons"]:
            rings = []
            for ring in poly:
                refs = []
                for seq in ring_arcs(ring, owners, neighbours):
                    rev = seq[::-1]
                    forward = seq <= rev
                    canon = seq if forward else rev
                    key = tuple(canon)
                    if key not in ids:
                        ids[key] = len(arcs)
                        arcs.append(canon)
                    refs.append(ids[key] if forward else ~ids[key])
                rings.append(refs)
            polygons.append(rings)
        bbox = [round(bbox[0] / GRID - 180, 3), round(bbox[1] / GRID - 90, 3),
                round(bbox[2] / GRID - 180, 3), round(bbox[3] / GRID - 90, 3)]
        table[code] = {"name": countries[code]["name"], "bbox": bbox, "polygons": polygons}
    return arcs, table


def seg_dist(p, a, b):
    dx, dy = b[0] - a[0], b[1] - a[1]
    length2 = dx * dx + dy * dy
    if length2 == 0:
        return math.hypot(p[0] - a[0], p[1] - a[1])
    return abs(dx * (p[1] - a[1]) - dy * (p[0] - a[0])) / math.sqrt(length2)


def simplify(points, tol):
    # Douglas-Peucker with fixed endpoints. Runs once per stored arc, so both countries keep the same points.
    # tol 0 keeps every point; it is the fallback for an arc of a ring that fails validation.
    if tol == 0:
        return list(points)
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        i, j = stack.pop()
        far, far_d = None, -1.0
        for k in range(i + 1, j):
            d = seg_dist(points[k], points[i], points[j])
            if d > far_d:
                far, far_d = k, d
        if far is not None and far_d > tol:
            keep[far] = True
            stack.append((i, far))
            stack.append((far, j))
    return [p for p, k in zip(points, keep) if k]


def encode_arc(points):
    return [list(points[0])] + [[x1 - x0, y1 - y0] for (x0, y0), (x1, y1) in zip(points, points[1:])]


def dumps(obj):
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def ring_points(refs, arcs):
    pts = []
    for ref in refs:
        seq = arcs[ref] if ref >= 0 else arcs[~ref][::-1]
        if pts and seq[0] != pts[-1]:
            raise SystemExit("arc join mismatch while rebuilding a ring")
        pts.extend(seq if not pts else seq[1:])
    if pts[0] != pts[-1]:
        raise SystemExit("ring is not closed after rebuilding from arcs")
    return pts[:-1]


def signed_area2(ring):
    return sum(ax * by - bx * ay for (ax, ay), (bx, by) in zip(ring, ring[1:] + ring[:1]))


def orient(a, b, c):
    v = (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])
    return (v > 0) - (v < 0)


def strict_crossing(ring):
    # Sweep over x: only segments whose x ranges overlap are compared. Adjacent segments are skipped.
    n = len(ring)
    segs = sorted((min(ring[i][0], ring[(i + 1) % n][0]), max(ring[i][0], ring[(i + 1) % n][0]), i) for i in range(n))
    for p, (_, x1, i) in enumerate(segs):
        a, b = ring[i], ring[(i + 1) % n]
        for x0, _, j in segs[p + 1:]:
            if x0 > x1:
                break
            if (j - i) % n in (1, n - 1):
                continue
            c, d = ring[j], ring[(j + 1) % n]
            if orient(a, b, c) * orient(a, b, d) < 0 and orient(c, d, a) * orient(c, d, b) < 0:
                return True
    return False


def ring_problems(ring, source):
    # source is the quantized ring before simplification; its orientation is the reference.
    found = []
    if len(set(ring)) < 3:
        found.append("fewer than 3 distinct vertices")
    area = signed_area2(ring)
    if area == 0:
        found.append("zero area")
    elif (area > 0) != (signed_area2(source) > 0):
        found.append("orientation changed")
    if strict_crossing(ring):
        found.append("self-intersection")
    return found


def simplify_valid(countries, arcs, table):
    # Every arc starts at DP tolerance. When a ring fails, each arc it uses drops to tol 0 (all points kept).
    # Arcs are shared, so a lowered arc changes the same points for every owner and borders stay identical.
    tols = [SIMPLIFY] * len(arcs)
    while True:
        simplified = [simplify(arc, tol) for arc, tol in zip(arcs, tols)]
        bad = []
        for code in sorted(table):
            sources = countries[code]["polygons"]
            for p, polygon in enumerate(table[code]["polygons"]):
                for r, refs in enumerate(polygon):
                    found = ring_problems(ring_points(refs, simplified), sources[p][r])
                    if found:
                        bad.append((code, p, r, refs, found))
        if not bad:
            return simplified
        lower = {ref if ref >= 0 else ~ref for _, _, _, refs, _ in bad for ref in refs} - \
            {k for k in range(len(arcs)) if tols[k] == 0}
        if not lower:
            for code, p, r, _, found in bad:
                print("unrepaired %s polygon %d ring %d: %s" % (code, p, r, ", ".join(found)))
            raise SystemExit("%d ring(s) still invalid with every arc at full resolution" % len(bad))
        print("invalid rings %d: keeping %d arc(s) at full resolution" % (len(bad), len(lower)))
        for k in lower:
            tols[k] = 0


def build(countries):
    for code in sorted(countries):
        countries[code]["polygons"] = drop_small(code, countries[code]["polygons"])
    owners, neighbours = topology(countries)
    arcs, table = assign_arcs(countries, owners, neighbours)
    simplified = simplify_valid(countries, arcs, table)
    header = HEADER % (RELEASE, GRID, GRID, GRID)
    world = "".join([
        header,
        "export const transform = %s;\n" % dumps({"scale": [1 / GRID, 1 / GRID], "translate": [-180, -90]}),
        "export const arcs = %s;\n" % dumps([encode_arc(arc) for arc in simplified]),
        "export const countries = %s;\n" % dumps(table),
    ])
    index = {code: {"name": c["name"], "bbox": c["bbox"]} for code, c in table.items()}
    index_json = json.dumps(index, sort_keys=True, indent=1, ensure_ascii=True) + "\n"
    print("countries %d, arcs %d, arc points %d" % (len(table), len(simplified), sum(len(a) for a in simplified)))
    return world, index_json


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def make_relief(out_dir):
    if not shutil.which("ffmpeg"):
        raise SystemExit("ffmpeg is needed for --relief")
    archive = cached(RELIEF_ZIP, RELIEF_URL, RELIEF_SHA256)
    tif = os.path.join(CACHE_DIR, RELIEF_TIF)
    if not os.path.exists(tif):
        with zipfile.ZipFile(archive) as z:
            z.extract(RELIEF_TIF, CACHE_DIR)
    out = os.path.join(out_dir, "relief.webp")
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", tif, "-vf", RELIEF_FILTER,
                    "-frames:v", "1", "-c:v", "libwebp", "-quality", RELIEF_QUALITY, out], check=True)
    print("relief.webp %d bytes" % os.path.getsize(out))


def main(argv=None):
    parser = argparse.ArgumentParser(description="Build the atlas3d map module from Natural Earth 1:50m countries.")
    parser.add_argument("--out-dir", default=DEFAULT_OUT)
    parser.add_argument("--relief", action="store_true", help="also write relief.webp through ffmpeg")
    args = parser.parse_args(argv)
    world, index_json = build(load_countries(cached(COUNTRIES, COUNTRIES_URL, COUNTRIES_SHA256)))
    os.makedirs(args.out_dir, exist_ok=True)
    write(os.path.join(args.out_dir, "world.js"), world)
    write(os.path.join(args.out_dir, "index.json"), index_json)
    print("world.js %d bytes, index.json %d bytes" % (len(world.encode("utf-8")), len(index_json.encode("utf-8"))))
    if args.relief:
        make_relief(args.out_dir)


if __name__ == "__main__":
    main()
